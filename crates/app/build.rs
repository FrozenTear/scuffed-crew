//! Parses the "What's changed" files (content/changelog/*.toml) at build
//! time. A broken file fails the build, including `dx build` in the
//! Containerfile, so it can never reach visitors. The checked entries are
//! written to `$OUT_DIR/changelog_entries.rs` as plain Rust, so the wasm
//! carries no TOML parser, no comment headers, and parses nothing at runtime.

use std::fmt::Write as _;
use std::path::Path;

use chrono::Datelike;

// The page's own types and parser, so the build and the page cannot drift.
#[allow(dead_code)]
#[path = "src/pages/changelog/model.rs"]
mod model;
#[allow(dead_code)]
#[path = "src/pages/changelog/parse.rs"]
mod parse;

use model::{Entry, Tab};

fn string_list(items: &[String]) -> String {
    let items: Vec<String> = items.iter().map(|s| format!("{s:?}.to_string()")).collect();
    format!("vec![{}]", items.join(", "))
}

fn optional(value: &Option<String>) -> String {
    match value {
        Some(s) => format!("Some({s:?}.to_string())"),
        None => "None".to_string(),
    }
}

fn emit(out: &mut String, func: &str, file: &str, entries: &[Entry]) {
    let _ = writeln!(
        out,
        "/// From `{file}`, newest first. Generated by build.rs."
    );
    let _ = writeln!(out, "fn {func}() -> Vec<Entry> {{");
    let _ = writeln!(out, "    vec![");
    for entry in entries {
        let groups: Vec<String> = entry
            .groups
            .iter()
            .map(|g| {
                format!(
                    "Group {{ kind: GroupKind::{:?}, items: {} }}",
                    g.kind,
                    string_list(&g.items)
                )
            })
            .collect();
        let _ = writeln!(
            out,
            "        Entry {{ version: {}, date: NaiveDate::from_ymd_opt({}, {}, {}).expect(\"checked by build.rs\"), changes: {}, groups: vec![{}], link: {} }},",
            optional(&entry.version),
            entry.date.year(),
            entry.date.month(),
            entry.date.day(),
            string_list(&entry.changes),
            groups.join(", "),
            optional(&entry.link),
        );
    }
    let _ = writeln!(out, "    ]");
    let _ = writeln!(out, "}}");
}

fn main() {
    for path in [
        "build.rs",
        "src/pages/changelog/model.rs",
        "src/pages/changelog/parse.rs",
        "content/changelog/site.toml",
        "content/changelog/tracker.toml",
    ] {
        println!("cargo::rerun-if-changed={path}");
    }

    let mut out = String::new();
    for (tab, file, func) in [
        (Tab::Site, "content/changelog/site.toml", "site_entries"),
        (
            Tab::Tracker,
            "content/changelog/tracker.toml",
            "tracker_entries",
        ),
    ] {
        let source = std::fs::read_to_string(file)
            .unwrap_or_else(|e| panic!("crates/app/{file}: cannot read it: {e}"));
        let entries = parse::parse(tab, &source)
            .unwrap_or_else(|e| panic!("crates/app/{file} is broken: {e}"));
        emit(&mut out, func, file, &entries);
    }

    let out_dir = std::env::var("OUT_DIR").expect("cargo sets OUT_DIR");
    let target = Path::new(&out_dir).join("changelog_entries.rs");
    std::fs::write(&target, out)
        .unwrap_or_else(|e| panic!("cannot write {}: {e}", target.display()));
}
